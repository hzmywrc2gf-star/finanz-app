import type { AppData, Transaction } from './types'
import { addMonths, monthEnd, monthStart } from './dates'
import { compareTransactionsDesc, summarizeRange } from './calc'
import type { CategorySum } from './calc'

export interface MonthCategorySum extends CategorySum {
  /** Expenses of the same category in the previous calendar month. */
  prevCents: number
}

export interface MonthTotals {
  incomeCents: number
  expenseCents: number
  saldoCents: number
}

export interface MonthSummary extends MonthTotals {
  /** saldo / income in percent, one decimal; null without income. */
  savingsRate: number | null
  /** Expenses generated by recurring rules. */
  recurringExpenseCents: number
  expenseByCategory: MonthCategorySum[]
  incomeByCategory: CategorySum[]
  /** The 5 largest expenses; ties newest first. */
  topExpenses: Transaction[]
  /** All booked transactions of the month, newest first. */
  transactions: Transaction[]
  previous: MonthTotals & { transactionCount: number }
  transactionCount: number
}

export interface MonthPoint extends MonthTotals {
  /** Month start, 'YYYY-MM-01'. */
  month: string
}

const TOP_EXPENSES = 5

/** Booked transactions of the calendar month containing `month` (any date of it works). */
export function monthSummary(data: AppData, month: string): MonthSummary {
  const from = monthStart(month)
  const prevFrom = addMonths(from, -1)
  const cur = summarizeRange(data.transactions, data.categories, from, monthEnd(from))
  const prev = summarizeRange(data.transactions, data.categories, prevFrom, monthEnd(prevFrom))
  const prevByCategory = new Map(prev.expenseByCategory.map((c) => [c.categoryId, c.cents]))

  const saldoCents = cur.incomeCents - cur.expenseCents
  const expenses = cur.transactions.filter((t) => t.kind === 'expense')
  return {
    incomeCents: cur.incomeCents,
    expenseCents: cur.expenseCents,
    saldoCents,
    savingsRate: cur.incomeCents > 0 ? Math.round((saldoCents * 1000) / cur.incomeCents) / 10 : null,
    recurringExpenseCents: expenses.reduce((s, t) => (t.recurringId ? s + t.amountCents : s), 0),
    expenseByCategory: cur.expenseByCategory.map((c) => ({ ...c, prevCents: prevByCategory.get(c.categoryId) ?? 0 })),
    incomeByCategory: cur.incomeByCategory,
    topExpenses: [...expenses]
      .sort((a, b) => b.amountCents - a.amountCents || compareTransactionsDesc(a, b))
      .slice(0, TOP_EXPENSES),
    transactions: cur.transactions,
    previous: {
      incomeCents: prev.incomeCents,
      expenseCents: prev.expenseCents,
      saldoCents: prev.incomeCents - prev.expenseCents,
      transactionCount: prev.transactions.length,
    },
    transactionCount: cur.transactions.length,
  }
}

/** The `count` months ending with `month`, oldest first. */
export function monthTrend(data: AppData, month: string, count = 6): MonthPoint[] {
  const last = monthStart(month)
  return Array.from({ length: count }, (_, i) => {
    const m = addMonths(last, i - (count - 1))
    const r = summarizeRange(data.transactions, data.categories, m, monthEnd(m))
    return { month: m, incomeCents: r.incomeCents, expenseCents: r.expenseCents, saldoCents: r.incomeCents - r.expenseCents }
  })
}

/** Upper end of a chart axis: the max rounded up to 1/2/3/4/5/6/8 × 10^n cents, so half of it is a tidy grid line too. */
export function niceAxisMax(maxCents: number): number {
  if (maxCents <= 0) return 0
  const pow = 10 ** Math.floor(Math.log10(maxCents))
  const step = [1, 2, 3, 4, 5, 6, 8, 10].find((s) => s * pow >= maxCents) ?? 10
  return step * pow
}
